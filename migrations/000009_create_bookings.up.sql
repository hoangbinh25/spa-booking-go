CREATE TABLE bookings (
    id              UUID            DEFAULT gen_random_uuid() PRIMARY KEY,
    booking_code    VARCHAR (30)    NOT NULL,
    branch_id       UUID            NOT NULL,
    customer_id     UUID            NOT NULL,
    status          VARCHAR (30)    DEFAULT 'PENDING' NOT NULL,
    source          VARCHAR (30)    DEFAULT 'ONLINE' NOT NULL,
    start_at        TIMESTAMPTZ     NOT NULL,
    end_at          TIMESTAMPTZ     NOT NULL,
    subtotal_amount NUMERIC (14, 2) DEFAULT 0 NOT NULL,
    discount_amount NUMERIC (14, 2) DEFAULT 0 NOT NULL,
    total_amount    NUMERIC (14, 2) DEFAULT 0 NOT NULL,
    note            TEXT           ,
    created_by      UUID           ,
    created_at      TIMESTAMPTZ     DEFAULT NOW() NOT NULL,
    updated_at      TIMESTAMPTZ     DEFAULT NOW() NOT NULL,
    CONSTRAINT uq_bookings_code UNIQUE (booking_code),
    CONSTRAINT fk_bookings_branch FOREIGN KEY (branch_id) REFERENCES branches (id),
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_bookings_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_bookings_time CHECK (start_at < end_at),
    CONSTRAINT chk_bookings_subtotal CHECK (subtotal_amount >= 0),
    CONSTRAINT chk_bookings_discount CHECK (discount_amount >= 0),
    CONSTRAINT chk_bookings_total CHECK (total_amount >= 0),
    CONSTRAINT chk_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT chk_bookings_source CHECK (source IN ('ONLINE', 'RECEPTIONIST', 'WALK_IN', 'AI_ASSISTANT'))
);